// Auditable build-time bundling only. No downloaded executable or runtime eval.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const files = {};
for (const name of ["launcher", "codex", "claude"]) {
  const result = await build({
    entryPoints: [`server/runtime/${name}.mjs`],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    write: false,
    minify: false,
    legalComments: "inline",
  });
  files[name + ".mjs"] = result.outputFiles[0].text;
}
const version = createHash("sha256").update(JSON.stringify(files)).digest("hex");
const generated =
  "// Generated by scripts/build-runtime.mjs from the included auditable runtime sources.\nexport const runtimeAssets = " +
  JSON.stringify({ version, files }) +
  " as const;\n";
const path = "server/runtime-assets.generated.ts";
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== generated)
    throw new Error("Runtime assets are stale; run npm run build:runtime");
} else await writeFile(path, generated);
